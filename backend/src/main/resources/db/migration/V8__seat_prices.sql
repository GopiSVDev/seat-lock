-- Money is integer paise (15000 = ₹150), like payment providers use

CREATE TABLE catalogue.show_price (
    id        bigint GENERATED BY DEFAULT AS IDENTITY,
    show_id   bigint       NOT NULL,
    seat_type varchar(255) NOT NULL,
    price     bigint       NOT NULL,
    CONSTRAINT pk_show_price PRIMARY KEY (id),
    CONSTRAINT uk_show_price_show_seat_type UNIQUE (show_id, seat_type),
    CONSTRAINT fk_show_price_show FOREIGN KEY (show_id) REFERENCES catalogue.shows (id),
    CONSTRAINT ck_show_price_seat_type CHECK (seat_type IN ('REGULAR', 'PREMIUM', 'RECLINER')),
    CONSTRAINT ck_show_price_price CHECK (price > 0)
);

-- Existing shows: default prices for the seat types their screen has
INSERT INTO catalogue.show_price (show_id, seat_type, price)
SELECT DISTINCT s.id, seat.seat_type,
       CASE seat.seat_type WHEN 'REGULAR' THEN 15000 WHEN 'PREMIUM' THEN 25000 ELSE 40000 END
FROM catalogue.shows s
JOIN catalogue.seat seat ON seat.screen_id = s.screen_id;

-- One-off backfills across schemas; application code never joins them
ALTER TABLE inventory.show_seat ADD COLUMN price bigint;

UPDATE inventory.show_seat ss
SET price = p.price
FROM catalogue.show_price p
WHERE p.show_id = ss.show_id
  AND p.seat_type = ss.seat_type;

ALTER TABLE booking.booking_seat ADD COLUMN price bigint;

UPDATE booking.booking_seat bs
SET price = ss.price
FROM inventory.show_seat ss
WHERE ss.id = bs.show_seat_id;

ALTER TABLE booking.booking ADD COLUMN total_amount bigint;

UPDATE booking.booking b
SET total_amount = (SELECT sum(bs.price) FROM booking.booking_seat bs WHERE bs.booking_id = b.id);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM inventory.show_seat WHERE price IS NULL)
        OR EXISTS (SELECT 1 FROM booking.booking_seat WHERE price IS NULL)
        OR EXISTS (SELECT 1 FROM booking.booking WHERE total_amount IS NULL) THEN
        RAISE EXCEPTION 'Rows without a price (seat of an unknown show?); fix them before migrating';
    END IF;
END $$;

ALTER TABLE inventory.show_seat
    ALTER COLUMN price SET NOT NULL,
    ADD CONSTRAINT ck_show_seat_price CHECK (price > 0);

ALTER TABLE booking.booking_seat
    ALTER COLUMN price SET NOT NULL,
    ADD CONSTRAINT ck_booking_seat_price CHECK (price > 0);

ALTER TABLE booking.booking
    ALTER COLUMN total_amount SET NOT NULL,
    ADD CONSTRAINT ck_booking_total_amount CHECK (total_amount > 0);
