-- theatre.city (text) → theatre.city_id. Existing rows are matched by city name or alias, ignoring case.
ALTER TABLE catalogue.theatre ADD COLUMN city_id bigint;

UPDATE catalogue.theatre t
SET city_id = coalesce(
        (SELECT c.id FROM catalogue.city c WHERE lower(c.name) = lower(trim(t.city)) ORDER BY c.id LIMIT 1),
        (SELECT a.city_id FROM catalogue.city_alias a WHERE lower(a.alias) = lower(trim(t.city))));

-- A theatre whose city can't be matched needs a human decision; fail instead of guessing
DO $$
DECLARE
    unmatched text;
BEGIN
    SELECT string_agg(DISTINCT city, ', ') INTO unmatched FROM catalogue.theatre WHERE city_id IS NULL;
    IF unmatched IS NOT NULL THEN
        RAISE EXCEPTION 'Theatres with unknown cities: %. Add the city or an alias first.', unmatched;
    END IF;
END $$;

ALTER TABLE catalogue.theatre
    ALTER COLUMN city_id SET NOT NULL,
    ADD CONSTRAINT fk_theatre_city FOREIGN KEY (city_id) REFERENCES catalogue.city (id),
    DROP COLUMN city;
