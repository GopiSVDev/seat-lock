-- Cities become reference data: theatres point to a city by id instead of free text, so "Chennai" and
-- "chenai" can no longer be two different cities. Search is typo tolerant through trigram similarity.

-- Trigram matching (similarity(), the % operator, gin_trgm_ops). Lives in public so every schema can use it.
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;

CREATE TABLE catalogue.city (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    name         varchar(100) NOT NULL,
    state        varchar(100) NOT NULL,
    popular_rank integer,
    CONSTRAINT pk_city PRIMARY KEY (id),
    CONSTRAINT ck_city_popular_rank CHECK (popular_rank > 0)
);

-- Same name can exist in two states (Aurangabad: Maharashtra and Bihar), never twice in one state
CREATE UNIQUE INDEX uk_city_name_state ON catalogue.city (lower(name), lower(state));
CREATE UNIQUE INDEX uk_city_popular_rank ON catalogue.city (popular_rank) WHERE popular_rank IS NOT NULL;
CREATE INDEX ix_city_name_trgm ON catalogue.city USING gin (name public.gin_trgm_ops);

-- Other names people type for a city: old names (Madras), short names (Trichy), spellings (Gurgaon)
CREATE TABLE catalogue.city_alias (
    id      bigint GENERATED BY DEFAULT AS IDENTITY,
    city_id bigint       NOT NULL,
    alias   varchar(100) NOT NULL,
    CONSTRAINT pk_city_alias PRIMARY KEY (id),
    CONSTRAINT fk_city_alias_city FOREIGN KEY (city_id) REFERENCES catalogue.city (id)
);

-- An alias points to exactly one city
CREATE UNIQUE INDEX uk_city_alias_alias ON catalogue.city_alias (lower(alias));
CREATE INDEX ix_city_alias_alias_trgm ON catalogue.city_alias USING gin (alias public.gin_trgm_ops);

