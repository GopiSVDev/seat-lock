-- Baseline: the schema Hibernate generated before migrations were introduced.
-- Schemas (catalogue, inventory, booking) are created by Flyway (spring.flyway.schemas).

-- catalogue -------------------------------------------------------------------

CREATE TABLE catalogue.movie (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    title            varchar(255) NOT NULL,
    description      text,
    duration_minutes integer      NOT NULL,
    certification    varchar(255) NOT NULL,
    release_date     date         NOT NULL,
    CONSTRAINT pk_movie PRIMARY KEY (id),
    CONSTRAINT ck_movie_certification CHECK (certification IN ('U', 'UA', 'A'))
);

CREATE TABLE catalogue.theatre (
    id      bigint GENERATED BY DEFAULT AS IDENTITY,
    name    varchar(255) NOT NULL,
    city    varchar(255) NOT NULL,
    address varchar(255) NOT NULL,
    CONSTRAINT pk_theatre PRIMARY KEY (id)
);

CREATE TABLE catalogue.screen (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    theatre_id bigint       NOT NULL,
    name       varchar(255) NOT NULL,
    CONSTRAINT pk_screen PRIMARY KEY (id),
    CONSTRAINT uk_screen_theatre_name UNIQUE (theatre_id, name),
    CONSTRAINT fk_screen_theatre FOREIGN KEY (theatre_id) REFERENCES catalogue.theatre (id)
);

CREATE TABLE catalogue.seat (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    screen_id   bigint       NOT NULL,
    row_label   varchar(255) NOT NULL,
    seat_number integer      NOT NULL,
    seat_type   varchar(255) NOT NULL,
    seat_rank   integer      NOT NULL,
    CONSTRAINT pk_seat PRIMARY KEY (id),
    CONSTRAINT uk_seat_screen_row_number UNIQUE (screen_id, row_label, seat_number),
    CONSTRAINT fk_seat_screen FOREIGN KEY (screen_id) REFERENCES catalogue.screen (id),
    CONSTRAINT ck_seat_seat_type CHECK (seat_type IN ('REGULAR', 'PREMIUM', 'RECLINER'))
);

CREATE TABLE catalogue.shows (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    movie_id   bigint       NOT NULL,
    screen_id  bigint       NOT NULL,
    start_time timestamptz(6) NOT NULL,
    end_time   timestamptz(6) NOT NULL,
    language   varchar(255) NOT NULL,
    format     varchar(255) NOT NULL,
    CONSTRAINT pk_shows PRIMARY KEY (id),
    CONSTRAINT fk_shows_movie FOREIGN KEY (movie_id) REFERENCES catalogue.movie (id),
    CONSTRAINT fk_shows_screen FOREIGN KEY (screen_id) REFERENCES catalogue.screen (id),
    CONSTRAINT ck_shows_format CHECK (format IN ('TWO_D', 'THREE_D', 'IMAX_2D', 'IMAX_3D', 'FOUR_DX'))
);

-- inventory -------------------------------------------------------------------
-- No foreign keys to catalogue: modules reference each other by plain id.

CREATE TABLE inventory.show_seat (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    show_id     bigint       NOT NULL,
    seat_id     bigint       NOT NULL,
    row_label   varchar(255) NOT NULL,
    seat_number integer      NOT NULL,
    seat_type   varchar(255) NOT NULL,
    seat_rank   integer      NOT NULL,
    status      varchar(255) NOT NULL,
    CONSTRAINT pk_show_seat PRIMARY KEY (id),
    CONSTRAINT uk_show_seat_show_seat UNIQUE (show_id, seat_id),
    CONSTRAINT ck_show_seat_seat_type CHECK (seat_type IN ('REGULAR', 'PREMIUM', 'RECLINER')),
    CONSTRAINT ck_show_seat_status CHECK (status IN ('AVAILABLE', 'BOOKED'))
);

-- booking ---------------------------------------------------------------------

CREATE TABLE booking.booking (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    show_id       bigint       NOT NULL,
    customer_name varchar(255) NOT NULL,
    status        varchar(255) NOT NULL,
    created_at    timestamptz(6) NOT NULL,
    CONSTRAINT pk_booking PRIMARY KEY (id),
    CONSTRAINT ck_booking_status CHECK (status IN ('CONFIRMED'))
);

CREATE TABLE booking.booking_seat (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    booking_id   bigint       NOT NULL,
    show_seat_id bigint       NOT NULL,
    seat_label   varchar(255) NOT NULL,
    status       varchar(255) NOT NULL,
    CONSTRAINT pk_booking_seat PRIMARY KEY (id),
    CONSTRAINT uk_booking_seat_booking_show_seat UNIQUE (booking_id, show_seat_id),
    CONSTRAINT fk_booking_seat_booking FOREIGN KEY (booking_id) REFERENCES booking.booking (id),
    CONSTRAINT ck_booking_seat_status CHECK (status IN ('CONFIRMED'))
);

-- A seat can be in many bookings over time (cancel + re-sale), but in only one confirmed booking.
CREATE UNIQUE INDEX uk_booking_seat_active_show_seat
    ON booking.booking_seat (show_seat_id) WHERE status = 'CONFIRMED';
