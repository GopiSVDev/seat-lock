-- One payment per booking: booking_id is the idempotency key for creating the Razorpay order
CREATE TABLE payment.payment (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY,
    booking_id          bigint       NOT NULL,
    customer_id         varchar(255) NOT NULL,
    amount              bigint       NOT NULL,
    currency            varchar(3)   NOT NULL,
    status              varchar(32)  NOT NULL,
    razorpay_order_id   varchar(64)  NOT NULL,
    razorpay_payment_id varchar(64),
    created_at          timestamptz  NOT NULL,
    updated_at          timestamptz  NOT NULL,
    CONSTRAINT pk_payment PRIMARY KEY (id),
    CONSTRAINT uk_payment_booking UNIQUE (booking_id),
    CONSTRAINT uk_payment_razorpay_order UNIQUE (razorpay_order_id),
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_status CHECK (status IN ('CREATED', 'CAPTURED', 'REFUND_PENDING', 'REFUNDED')),
    CONSTRAINT ck_payment_captured CHECK ((status = 'CREATED') = (razorpay_payment_id IS NULL))
);

CREATE INDEX ix_payment_razorpay_payment ON payment.payment (razorpay_payment_id);

-- Every try at paying an order (a declined card, then UPI...); the order stays open until one succeeds
CREATE TABLE payment.payment_attempt (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY,
    payment_id          bigint       NOT NULL,
    razorpay_payment_id varchar(64)  NOT NULL,
    status              varchar(32)  NOT NULL,
    method              varchar(32),
    error_description   varchar(500),
    created_at          timestamptz  NOT NULL,
    CONSTRAINT pk_payment_attempt PRIMARY KEY (id),
    CONSTRAINT uk_payment_attempt_razorpay_payment UNIQUE (razorpay_payment_id),
    CONSTRAINT fk_payment_attempt_payment FOREIGN KEY (payment_id) REFERENCES payment.payment (id),
    CONSTRAINT ck_payment_attempt_status CHECK (status IN ('CAPTURED', 'FAILED'))
);

CREATE INDEX ix_payment_attempt_payment ON payment.payment_attempt (payment_id);

-- Full refunds only, so at most one per payment
CREATE TABLE payment.refund (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    payment_id         bigint      NOT NULL,
    razorpay_refund_id varchar(64) NOT NULL,
    amount             bigint      NOT NULL,
    reason             varchar(32) NOT NULL,
    created_at         timestamptz NOT NULL,
    processed_at       timestamptz,
    CONSTRAINT pk_refund PRIMARY KEY (id),
    CONSTRAINT uk_refund_payment UNIQUE (payment_id),
    CONSTRAINT uk_refund_razorpay_refund UNIQUE (razorpay_refund_id),
    CONSTRAINT fk_refund_payment FOREIGN KEY (payment_id) REFERENCES payment.payment (id),
    CONSTRAINT ck_refund_amount CHECK (amount > 0),
    CONSTRAINT ck_refund_reason CHECK (reason IN ('BOOKING_FAILED', 'BOOKING_CANCELLED'))
);
